#!/bin/bash

# Claude-CodeSentinel Target Setup Script
# Configures the framework to analyze a target project

echo "═══════════════════════════════════════════════════════════"
echo "🔧 Claude-CodeSentinel Target Configuration"
echo "═══════════════════════════════════════════════════════════"
echo ""

# Function to display help
show_help() {
    echo "Usage: ./setup-target.sh [OPTIONS]"
    echo ""
    echo "Options:"
    echo "  -p, --path PATH      Set the target project path"
    echo "  -r, --relative       Use relative path (default: ../ for parent directory)"
    echo "  -a, --absolute PATH  Use absolute path to project"
    echo "  -t, --test           Test configuration with current settings"
    echo "  -h, --help           Show this help message"
    echo ""
    echo "Examples:"
    echo "  ./setup-target.sh                    # Configure for parent directory (default)"
    echo "  ./setup-target.sh -p ../my-project   # Configure for sibling directory"
    echo "  ./setup-target.sh -a /path/to/project # Configure with absolute path"
    echo "  ./setup-target.sh -t                 # Test current configuration"
    echo ""
    exit 0
}

# Function to test configuration
test_config() {
    echo "🔍 Testing current configuration..."
    echo ""

    # Load configuration
    if [ -f ".claude/target.config" ]; then
        source .claude/target.config
    fi

    # Set target path with defaults
    TARGET_PATH="${TARGET_PATH:-../}"

    # Resolve to absolute path
    ABS_PATH="$(cd "$(dirname "$TARGET_PATH")" 2>/dev/null && pwd)/$(basename "$TARGET_PATH")"

    if [ -d "$ABS_PATH" ]; then
        echo "✅ Target directory exists: $ABS_PATH"
        echo ""
        echo "📊 Project Statistics:"
        echo "  Java files: $(find "$ABS_PATH" -name "*.java" 2>/dev/null | grep -v "/.claude/" | wc -l)"
        echo "  Python files: $(find "$ABS_PATH" -name "*.py" 2>/dev/null | grep -v "/.claude/" | wc -l)"
        echo "  JavaScript files: $(find "$ABS_PATH" -name "*.js" 2>/dev/null | grep -v "/.claude/" | wc -l)"
        echo "  Go files: $(find "$ABS_PATH" -name "*.go" 2>/dev/null | grep -v "/.claude/" | wc -l)"

        # Check for CLAUDE.md in target
        if [ -f "$ABS_PATH/CLAUDE.md" ]; then
            echo ""
            echo "✅ Found CLAUDE.md in target project"
        fi
    else
        echo "❌ Target directory does not exist: $ABS_PATH"
        exit 1
    fi

    exit 0
}

# Parse command line arguments
TARGET_PATH=""
MODE="relative"

while [[ $# -gt 0 ]]; do
    case $1 in
        -p|--path)
            TARGET_PATH="$2"
            shift 2
            ;;
        -r|--relative)
            MODE="relative"
            shift
            ;;
        -a|--absolute)
            TARGET_PATH="$2"
            MODE="absolute"
            shift 2
            ;;
        -t|--test)
            test_config
            ;;
        -h|--help)
            show_help
            ;;
        *)
            echo "Unknown option: $1"
            show_help
            ;;
    esac
done

# If no path specified, ask user
if [ -z "$TARGET_PATH" ]; then
    echo "Current framework location: $(pwd)"
    echo ""
    echo "Where is the project you want to analyze?"
    echo ""
    echo "1) Parent directory (../) - Default for framework as subdirectory"
    echo "2) Specific relative path"
    echo "3) Absolute path"
    echo ""
    read -p "Select option [1-3] (default: 1): " choice

    case $choice in
        2)
            read -p "Enter relative path from framework directory: " TARGET_PATH
            MODE="relative"
            ;;
        3)
            read -p "Enter absolute path to project: " TARGET_PATH
            MODE="absolute"
            ;;
        *)
            TARGET_PATH="../"
            MODE="relative"
            ;;
    esac
fi

# Validate target path
if [ "$MODE" = "relative" ]; then
    # Check if relative path exists
    if [ ! -d "$TARGET_PATH" ]; then
        echo "❌ Directory does not exist: $TARGET_PATH"
        exit 1
    fi
    ABS_PATH="$(cd "$TARGET_PATH" && pwd)"
else
    # Check if absolute path exists
    if [ ! -d "$TARGET_PATH" ]; then
        echo "❌ Directory does not exist: $TARGET_PATH"
        exit 1
    fi
    ABS_PATH="$TARGET_PATH"
    # Convert to relative if possible for cleaner config
    RELATIVE_PATH="$(realpath --relative-to="$(pwd)" "$ABS_PATH" 2>/dev/null)"
    if [ $? -eq 0 ]; then
        TARGET_PATH="$RELATIVE_PATH"
    fi
fi

# Update configuration file
echo "📝 Writing configuration to .claude/target.config..."
cat > .claude/target.config << EOF
# Target Project Configuration
# This file defines the path to the project to be analyzed
#
# Generated by setup-target.sh on $(date)

# Target path - relative to the framework directory
TARGET_PATH="$TARGET_PATH"

# Absolute path (for reference)
# $ABS_PATH

# Exclude patterns - directories to skip during analysis
EXCLUDE_DIRS="node_modules,vendor,.git,dist,build,target,.claude,venv,__pycache__"

# Include only specific directories (leave empty to include all)
# INCLUDE_DIRS="src,lib,app"

# Report output directory (relative to framework root)
REPORT_DIR="./reports"

# Framework behavior
ANALYZE_FRAMEWORK_ITSELF="false"  # Set to true to include framework code in analysis
EOF

echo "✅ Configuration saved!"
echo ""
echo "═══════════════════════════════════════════════════════════"
echo "📋 Configuration Summary:"
echo "═══════════════════════════════════════════════════════════"
echo "  Target Path: $TARGET_PATH"
echo "  Absolute: $ABS_PATH"
echo "  Framework: $(pwd)"
echo ""

# Show project statistics
echo "📊 Target Project Statistics:"
echo "  Java files: $(find "$ABS_PATH" -name "*.java" 2>/dev/null | grep -v "/.claude/" | wc -l)"
echo "  Python files: $(find "$ABS_PATH" -name "*.py" 2>/dev/null | grep -v "/.claude/" | wc -l)"
echo "  JavaScript files: $(find "$ABS_PATH" -name "*.js" 2>/dev/null | grep -v "/.claude/" | wc -l)"
echo "  Go files: $(find "$ABS_PATH" -name "*.go" 2>/dev/null | grep -v "/.claude/" | wc -l)"

# Check for CLAUDE.md in target
if [ -f "$ABS_PATH/CLAUDE.md" ]; then
    echo ""
    echo "✅ Found CLAUDE.md in target project"
    echo "   The framework will respect project-specific instructions"
fi

echo ""
echo "═══════════════════════════════════════════════════════════"
echo "🚀 Ready to analyze!"
echo "═══════════════════════════════════════════════════════════"
echo ""
echo "You can now run the review command:"
echo "  /full-review"
echo ""
echo "The framework will analyze: $ABS_PATH"
echo ""